CREATE TABLE Student
( 
Stu_id INT CONSTRAINT pk_ PRIMARY KEY,
Name VARCHAR(50) NOT NULL,
Adhar BIGINT CONSTRAINT UK1_ UNIQUE,
Contact_no BIGINT CONSTRAINT UK2_ UNIQUE,
Age INT CONSTRAINT CK1_ CHECK (Age >= 18),
Fees INT CONSTRAINT CK2_ CHECK (Fees > 2000),
City VARCHAR(50) NOT NULL,
join_date DATE CONSTRAINT DK_ DEFAULT getdate()
);

